#!/usr/bin/env bash
# =============================================================================
#  Vivo-Router — blocklist snapshot
#
#  The dashboard's Blocklist panel and suricata-autoblock.py add IPs to the
#  live set "table inet dashboard_blocks / manual_blocked" with `nft add
#  element`, which never touches a file — so without this, every block is
#  lost on reboot. This script dumps that table to the file
#  /etc/nftables.conf includes, keeping the hundreds of auto-blocked IPs out
#  of the main firewall config while still persisting them.
#
#  Run every 5 minutes by vivo-blocklist-save.timer. Deployed copy lives at
#  /usr/local/sbin/vivo-save-blocklist (root-owned, so the root timer never
#  executes a file under /home that a non-root user can edit).
#
#  Safe to run any time: it never installs a snapshot that fails
#  `nft -c`, only rewrites the file when the contents changed, and keeps the
#  previous version as blocklist.nft.prev.
# =============================================================================

set -euo pipefail

OUT=/etc/nftables.d/blocklist.nft
NFT=/usr/sbin/nft

# Table not created yet (early boot, before the include or the dashboard
# has run) — keep the last good snapshot rather than writing an empty one.
$NFT list table inet dashboard_blocks &>/dev/null || exit 0

mkdir -p "$(dirname "$OUT")"
tmp=$(mktemp "${OUT}.XXXXXX")
trap 'rm -f "$tmp"' EXIT

{
    echo "#!/usr/sbin/nft -f"
    echo "# Vivo-Router blocklist — included by /etc/nftables.conf."
    echo "# Generated by save-blocklist.sh from the live set; manual edits are"
    echo "# overwritten. Block/unblock from the dashboard's Blocklist panel."
    echo
    echo "destroy table inet dashboard_blocks"
    $NFT list table inet dashboard_blocks
} > "$tmp"

$NFT -c -f "$tmp"

if ! cmp -s "$tmp" "$OUT"; then
    [[ -f "$OUT" ]] && cp -p "$OUT" "${OUT}.prev"
    chmod 644 "$tmp"
    mv "$tmp" "$OUT"
    echo "blocklist saved: $(grep -oE '[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+' "$OUT" | wc -l) IPs"
fi
